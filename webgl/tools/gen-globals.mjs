#!/usr/bin/env node
/* Regenerates js/shaders/globals.glsl from js/params.js. Run: node tools/gen-globals.mjs */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { GROUPS, RAMPS, CLAIMS } from '../js/params.js';
import { layoutUniforms, vectorCost } from '../js/uniforms.js';

const here = dirname(fileURLToPath(import.meta.url));
const L = layoutUniforms(GROUPS, RAMPS);
const out = join(here, '..', 'js', 'shaders', 'globals.glsl');
writeFileSync(out, L.glsl + '\n');
/* the evidence mosaic needs the claims list in the fragment shader */
const CATS = ['material', 'bio', 'geo', 'cognitive', 'tech', 'eco'];
const catIdx = (c) => Math.max(0, CATS.indexOf(c.cat));
const conf = (c) => /measured|observed/.test(c.lvl) ? 2 : (/contested|mixed|emerging|early|suggestive|single|anecdotal/.test(c.lvl) ? 0 : 1);
const claimsSrc = `/* GENERATED by tools/gen-globals.mjs from CLAIMS in js/params.js.
   category 0 material · 1 bio · 2 geo · 3 cognitive · 4 tech · 5 eco
   confidence 2 measured/observed · 1 plausible · 0 weak. The overlay draws the
   confidence, so a claim’s weakness is visible rather than hidden. */
const int CLAIM_N = ${CLAIMS.length};
const int CLAIM_CAT[${CLAIMS.length}] = int[${CLAIMS.length}](${CLAIMS.map(c => catIdx(c)).join(', ')});
const int CLAIM_Y0[${CLAIMS.length}] = int[${CLAIMS.length}](${CLAIMS.map(c => c.band[0]).join(', ')});
const int CLAIM_Y1[${CLAIMS.length}] = int[${CLAIMS.length}](${CLAIMS.map(c => c.band[1]).join(', ')});
const int CLAIM_CONF[${CLAIMS.length}] = int[${CLAIMS.length}](${CLAIMS.map(c => conf(c)).join(', ')});
`;
writeFileSync(join(here, '..', 'js', 'shaders', 'claims.glsl'), claimsSrc);
console.log(`claims.glsl written: ${CLAIMS.length} claims`);

console.log(`globals.glsl written: ${L.uniforms.length} knobs in ${L.floats.length}+${L.ints.length}+${L.cols.length} bundles, uniform-vector cost ${vectorCost(L)}`);
