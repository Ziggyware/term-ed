/* =============================================================================
   uniforms.js — packs several hundred knobs into a couple of dozen vec4s.

   GLES3 guarantees only 224 fragment uniform vectors. This page has ~250 live
   knobs, so uniforms are bundled four floats to a vec4 and aliased back to
   readable names with the preprocessor:

       uniform vec4 uPk0;
       #define u_wet uPk0.x

   The alias table is generated from params.js, and js/shaders/globals.glsl is
   generated from the same table (tools/gen-globals.mjs), so the shader sources
   and the uploader can never drift apart.
   ============================================================================= */
'use strict';

export const DERIVED_VERTEX = []; // nothing lives in the vertex stage

/* Uniforms the renderer computes rather than the user setting them. */
export const DERIVED = [
  { n: 'uTanHalfFov', t: 'F' }, { n: 'uLC', t: 'F' },
  { n: 'uRes', t: 'V3' }, { n: 'uTime', t: 'F' }, { n: 'uPulse', t: 'F' },
  { n: 'uPulse2', t: 'F' }, { n: 'uFrame', t: 'F' }, { n: 'uDT', t: 'F' },
  { n: 'uMode', t: 'I' }, { n: 'uAspect', t: 'F' }, { n: 'uFov', t: 'F' },
  { n: 'uMouse', t: 'V3' }, { n: 'uCamO', t: 'V3' }, { n: 'uCamR', t: 'V3' },
  { n: 'uCamU', t: 'V3' }, { n: 'uCamF', t: 'V3' }, { n: 'uModeToggle', t: 'I' },
  { n: 'uLayout', t: 'V3' }, { n: 'uVecA', t: 'V3' },
];

/* samplers the modes need; declared alongside the packed knobs */
export const SAMPLERS = ['uMemory'];
export function isUniformParam(g) { return !!g.u; }

const rampIndex = (name, ramps) => Math.max(0, ramps.indexOf(name));

/**
 * Build the packed layout for the shader-visible knobs.
 * @returns {{glsl:string, floats:Array, ints:Array, cols:Array,
 *            slot:Map<string,{block:number,comp:number,type:string}>,
 *            uniforms:Array<{name:string,kind:string,block:number,comp:number}>}}
 */
export function layoutUniforms(groups, ramps = []) {
  const floats = [], ints = [], cols = [];
  const slot = new Map();
  const uniforms = [];

  for (const g of groups) {
    if (!isUniformParam(g)) continue;
    const kind = (g.t === 'F') ? 'F' : (g.t === 'C') ? 'C' : 'I';
    const key = g.k || g.u;
    if (kind === 'C') {
      cols.push({ n: 0 });
      slot.set(key, { block: cols.length - 1, comp: 0, type: kind });
      uniforms.push({ name: g.u, kind, block: cols.length - 1, comp: 0, src: g });
      continue;
    }
    const b = (kind === 'F') ? floats : ints;
    let entry = b[b.length - 1];
    if (!entry || entry.n >= 4) { entry = { n: 0 }; b.push(entry); }
    const comp = entry.n++;
    slot.set(key, { block: b.length - 1, comp, type: kind });
    uniforms.push({ name: g.u, kind, block: b.length - 1, comp, src: g });
  }

  // serialise ramps as ints so palettes can be picked in-shader
  const rampName = '__ramps';

  const lines = [];
  lines.push('/* GENERATED by tools/gen-globals.mjs — edit js/params.js instead.');
  lines.push('   Packed knob storage: four floats per vec4, aliased to real names. */');
  for (let i = 0; i < floats.length; i++) lines.push(`uniform vec4 uPk${i};`);
  for (let i = 0; i < ints.length; i++) lines.push(`uniform ivec4 uIk${i};`);
  for (let i = 0; i < cols.length; i++) lines.push(`uniform vec3 uCk${i};`);
  lines.push('');

  for (const u of uniforms) {
    const blk = u.kind === 'C' ? `uCk${u.block}` : (u.kind === 'F' ? `uPk${u.block}` : `uIk${u.block}`);
    const v = u.kind === 'C' ? blk : `${blk}.${'xyzw'[u.comp]}`;
    lines.push(`#define ${u.name} ${v}`);
  }
  lines.push('');
  lines.push('/* derived */');
  for (const d of DERIVED) {
    if (d.t === 'V3') lines.push(`uniform vec3 ${d.n};`);
    else if (d.t === 'I') lines.push(`uniform int ${d.n};`);
    else lines.push(`uniform float ${d.n};`);
  }
  for (const sm of SAMPLERS) lines.push(`uniform sampler2D ${sm};`);
  lines.push(`const int RAMP_COUNT = ${Math.max(1, ramps.length)};`);
  lines.push(`#define RAMP_NONE -1`);
  for (const [i, r] of ramps.entries()) lines.push(`const int RAMP_${r.toUpperCase().replace(/[^A-Z0-9]/g, '_')} = ${i};`);
  lines.push('');
  return { glsl: lines.join('\n'), floats, ints, cols, slot, uniforms, rampName, ramps };
}

/* ------------------------------------------------------------------ values -- */
export function srgbToLinear(c) {
  return (c <= 0.04045) ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
}
export function hexToLinear(hex) {
  const h = String(hex).replace('#', '');
  const n = parseInt(h.length === 3 ? h.split('').map(x => x + x).join('') : h, 16) || 0;
  return [srgbToLinear(((n >> 16) & 255) / 255), srgbToLinear(((n >> 8) & 255) / 255), srgbToLinear((n & 255) / 255)];
}
export function linearToHex(c) {
  const s = (x) => {
    const v = x <= 0.0031308 ? x * 12.92 : 1.055 * Math.pow(Math.max(0, x), 1 / 2.4) - 0.055;
    return Math.round(Math.min(1, Math.max(0, v)) * 255).toString(16).padStart(2, '0');
  };
  return '#' + s(c[0]) + s(c[1]) + s(c[2]);
}

/** Coerce a stored config value into what the shader wants for its kind. */
export function toShaderValue(g, raw, ramps = []) {
  switch (g.t) {
    case 'F': return Number(raw) || 0;
    case 'B': return raw ? 1 : 0;
    case 'I': return Math.round(Number(raw) || 0);
    case 'S': {
      const i = (g.o || []).indexOf(raw);
      return i < 0 ? 0 : i;
    }
    case 'C': return hexToLinear(raw);
    default: return Number(raw) || 0;
  }
}

/**
 * Pack a whole config into flat arrays ready for gl.uniform*.
 * Returns { f: Float32Array[], i: Int32Array[], c: Float32Array[] }.
 */
export function packUniforms(layout, values, ramps = []) {
  const f = layout.floats.map(() => new Float32Array(4));
  const i = layout.ints.map(() => new Int32Array(4));
  const c = layout.cols.map(() => new Float32Array(3));
  for (const g of values) {
    const s = layout.slot.get(g.key);
    if (!s) continue;
    const v = toShaderValue(g.def, g.raw, ramps);
    if (s.type === 'C') { const t = c[s.block]; t[0] = v[0]; t[1] = v[1]; t[2] = v[2]; }
    else if (s.type === 'F') f[s.block][s.comp] = v;
    else i[s.block][s.comp] = v | 0;
  }
  return { f, i, c };
}

/** Number of uniform vectors this layout costs — checked against the GL limit. */
export function vectorCost(layout) {
  return layout.floats.length + layout.ints.length + layout.cols.length + DERIVED.length + SAMPLERS.length + 4;
}
